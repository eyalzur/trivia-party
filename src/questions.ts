export interface Question {
  id: string;
  q: string;
  a: string;
  wrong: [string, string, string];
}

export interface Category {
  key: string;
  label: string;
  questions: Question[];
}

function cat(key: string, label: string, rows: [string, string, string, string, string][]): Category {
  return {
    key,
    label,
    questions: rows.map(([q, a, w1, w2, w3], i) => ({ id: `${key}-${i}`, q, a, wrong: [w1, w2, w3] })),
  };
}

