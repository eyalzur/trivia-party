export function getCategory(key: string): Category | undefined {
  return CATEGORIES.find((c) => c.key === key);
}

export function getQuestion(categoryKey: string, questionId: string): Question | undefined {
  return getCategory(categoryKey)?.questions.find((q) => q.id === questionId);
}

export function usedKey(categoryKey: string, questionId: string): string {
  return `${categoryKey}:${questionId}`;
}

export function pickRandomQuestion(categoryKey: string, usedKeys: string[]): Question | undefined {
  const category = getCategory(categoryKey);
  if (!category) return undefined;
  const used = new Set(usedKeys);
  const remaining = category.questions.filter((q) => !used.has(usedKey(categoryKey, q.id)));
  const pool = remaining.length ? remaining : category.questions;
  return pool[Math.floor(Math.random() * pool.length)];
}
