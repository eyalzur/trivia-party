export interface Question {
  id: string;
  q: string;
  a: string;
}

export interface Category {
  key: string;
  label: string;
  questions: Question[];
}

function cat(key: string, label: string, pairs: [string, string][]): Category {
  return {
    key,
    label,
    questions: pairs.map(([q, a], i) => ({ id: `${key}-${i}`, q, a })),
  };
}

